import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { MODULES, compile } from '../../scripts/build-dafny.mjs';

function hasDafny(): boolean {
	try {
		execFileSync('dafny', ['--version'], { stdio: 'ignore' });
		return true;
	} catch {
		return false;
	}
}

// The committed JS is what runs; the .dfy is what was proved. This keeps them the same file.
// Skipped where dafny is not installed (CI): `bun run build:dafny` regenerates it locally.
describe('generated Dafny output', () => {
	for (const entry of MODULES) {
		it.skipIf(!hasDafny())(
			`${entry.out} matches ${entry.source}`,
			() => {
				const committed = readFileSync(join(process.cwd(), entry.out), 'utf8');
				expect(committed).toBe(compile(entry));
			},
			120_000
		);
		it(`${entry.out} says what it was generated from`, () => {
			const committed = readFileSync(join(process.cwd(), entry.out), 'utf8');
			expect(committed).toContain(`GENERATED by scripts/build-dafny.mjs from ${entry.source}`);
		});
	}
});
