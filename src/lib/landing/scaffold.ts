/**
 * Text for `bun run landing new <family> <slug>`: an empty page stub and the
 * regenerated pages index. Stubs carry structure and TODO markers only, never
 * prose — the content must be written by a person (docs/SEO_LANDING_PAGES.md).
 *
 * Pure string builders; the file I/O lives in scripts/landing.ts.
 */
import type { FamilyKey } from './types';

export const FAMILY_KEYS: readonly FamilyKey[] = ['who', 'where', 'what', 'when', 'why'];

export const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export const isFamilyKey = (value: string): value is FamilyKey =>
	(FAMILY_KEYS as readonly string[]).includes(value);

export function pageStub(family: FamilyKey, slug: string): string {
	if (!SLUG.test(slug)) throw new Error(`slug "${slug}" must be lowercase words joined by "-"`);
	const tie =
		family === 'where'
			? `\t// Required on a region page: the real reason this place has a page.\n\ttie: { kind: 'other', note: '' },\n`
			: '';
	return `import { definePage } from '../../../define';

/**
 * TODO(owner): write this page by hand. Before writing, answer: does it say
 * something true and useful that no other page on the site says? If it would
 * only change a noun on another page, delete this file instead.
 */
export default definePage({
	family: '${family}',
	slug: '${slug}',
	draft: true,
	name: '',
	title: '',
	description: '',
	h1: '',
	lede: '',
	blurb: '',
	sectionsHeading: '',
	sections: [
		{ heading: '', body: '' },
		{ heading: '', body: '' },
		{ heading: '', body: '' }
	],
	faq: [
		{ question: '', answer: '' },
		{ question: '', answer: '' },
		{ question: '', answer: '' }
	],
${tie}	notes: ['TODO(owner): fill every field, check every claim, then delete draft: true']
});
`;
}

/** `who/restaurants` → `who_restaurants`, a valid import identifier. */
const ident = (entry: string) => entry.replace(/[/-]/g, '_');

/** The pages index, from `family/slug` entries, sorted for stable diffs. */
export function pagesIndex(entries: string[]): string {
	const sorted = [...entries].sort();
	const imports = sorted.map((e) => `import ${ident(e)} from './${e}';`).join('\n');
	const list = sorted.map((e) => `\t${ident(e)}`).join(',\n');
	return `// Generated by \`bun run landing index\`. Do not edit by hand; add a page file and re-run it.
import type { LandingPage } from '../../types';
${imports}

export const PAGES: LandingPage[] = [
${list}
];
`;
}
