#!/usr/bin/env node
/**
 * Regenerates packages/commerce/src/price-level-index.ts from the World Bank.
 *
 * Ported from Ammoura's scripts/update-price-index.mjs (2026-10-25). Run it by
 * hand when you want fresh data, then review the diff and commit it. Nothing
 * fetches this at runtime: the site ships the table it was built with.
 *
 * The index is the price level ratio: how much the same basket costs in a
 * country, against the US, at market exchange rates. 1.0 is US prices; 0.25
 * means things cost about a quarter of what they cost in the US.
 *
 * The World Bank archived its own ratio series (PA.NUS.PPPC.RF), so it is
 * computed here from the two series it was made from:
 *   PPP conversion factor, GDP (LCU per international $)   PA.NUS.PPP
 *   Official exchange rate (LCU per US$, period average)    PA.NUS.FCRF
 * ratio = PPP / exchange rate, from the latest year that has both.
 *
 * Run: bun run update:price-index   (or: node scripts/update-price-index.mjs)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'packages/commerce/src/price-level-index.ts');
const API = 'https://api.worldbank.org/v2';

const PLAUSIBLE_MIN = 0.08;
const PLAUSIBLE_MAX = 2;
/** Fewer rows than this means the API answered badly; keep the file we have. */
const MIN_COUNTRIES = 150;

/** @param {string} url */
async function getJson(url) {
	const res = await fetch(url);
	if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
	return res.json();
}

/**
 * @param {string} indicator
 * @param {string} range
 * @returns {Promise<Map<string, Map<number, number>>>}
 */
async function series(indicator, range) {
	const body = await getJson(
		`${API}/country/all/indicator/${indicator}?format=json&per_page=20000&date=${range}`
	);
	if (!Array.isArray(body) || !Array.isArray(body[1])) {
		throw new Error(`${indicator}: ${JSON.stringify(body).slice(0, 200)}`);
	}
	/** iso2 -> year -> value */
	/** @type {Map<string, Map<number, number>>} */
	const out = new Map();
	for (const row of body[1]) {
		if (row.value === null) continue;
		const code = row.country.id;
		if (!out.has(code)) out.set(code, new Map());
		out.get(code)?.set(Number(row.date), row.value);
	}
	return out;
}

/** Real countries only: the World Bank also reports regions and income groups (region id "NA"). */
async function countryCodes() {
	const body = await getJson(`${API}/country?format=json&per_page=400`);
	if (!Array.isArray(body) || !Array.isArray(body[1])) throw new Error('country list unreadable');
	return new Set(
		body[1]
			.filter((/** @type {any} */ c) => c.region?.id !== 'NA' && /^[A-Z]{2}$/.test(c.id))
			.map((/** @type {any} */ c) => c.id)
	);
}

/**
 * Pure, so it can be tested without the network: rows from the three fetched maps.
 * @param {Map<string, Map<number, number>>} ppp
 * @param {Map<string, Map<number, number>>} fx
 * @param {Set<string>} known
 */
export function buildRows(ppp, fx, known) {
	/** @type {{ code: string; year: number; ratio: number }[]} */
	const rows = [];
	for (const [code, years] of ppp) {
		if (!known.has(code) || !fx.has(code)) continue;
		const rates = /** @type {Map<number, number>} */ (fx.get(code));
		const common = [...years.keys()].filter((y) => rates.has(y));
		if (common.length === 0) continue;
		const year = Math.max(...common);
		const ratio = /** @type {number} */ (years.get(year)) / /** @type {number} */ (rates.get(year));
		// Outside this range the two series disagree about the currency (Liberia
		// reports PPP in US$ and the exchange rate in L$, giving 0.002) or the
		// official rate is far from the real one (Iran, 2.2). Such a figure would
		// price a country wrongly, so the country is left out and pays base price.
		if (!Number.isFinite(ratio) || ratio < PLAUSIBLE_MIN || ratio > PLAUSIBLE_MAX) continue;
		rows.push({ code, year, ratio: Math.round(ratio * 1000) / 1000 });
	}
	return rows.sort((a, b) => a.code.localeCompare(b.code));
}

/**
 * @param {{ code: string; year: number; ratio: number }[]} rows
 * @param {string} today
 */
export function render(rows, today) {
	return `/**
 * Price level ratio by country: what the same basket of goods costs there,
 * against the US, at market exchange rates. 1.0 is US prices.
 *
 * GENERATED by scripts/update-price-index.mjs on ${today} from the World Bank
 * (PA.NUS.PPP ÷ PA.NUS.FCRF, latest year with both). Do not edit by hand;
 * run the script and review the diff. A country that is missing has no data
 * and is priced as the base price. Nothing fetches this at runtime.
 */

/** ISO 3166-1 alpha-2 → [ratio to US prices, data year]. */
export const PRICE_LEVEL_INDEX: Readonly<Record<string, readonly [number, number]>> = {
${rows.map((r) => `\t${r.code}: [${r.ratio}, ${r.year}]`).join(',\n')}
};

export const PRICE_LEVEL_INDEX_UPDATED = '${today}';
`;
}

async function main() {
	const thisYear = new Date().getUTCFullYear();
	const range = `${thisYear - 8}:${thisYear}`;
	const [ppp, fx, known] = await Promise.all([
		series('PA.NUS.PPP', range),
		series('PA.NUS.FCRF', range),
		countryCodes()
	]);
	const rows = buildRows(ppp, fx, known);
	if (rows.length < MIN_COUNTRIES) {
		throw new Error(`Only ${rows.length} countries came back; not writing.`);
	}
	writeFileSync(OUT, render(rows, new Date().toISOString().slice(0, 10)));
	console.log(`Wrote ${rows.length} countries to ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
