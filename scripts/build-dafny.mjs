// Verify dafny/LoginThrottle.dfy, compile it to JS, and wrap the CommonJS output as an ES module
// at src/lib/server/generated/login-throttle-core.js. Needs `dafny` (4.11) on PATH.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';

const root = new URL('..', import.meta.url).pathname;
const work = mkdtempSync(join(process.env.TMPDIR || join(homedir(), '.tmp'), 'dafny-'));
try {
	execFileSync(
		'dafny',
		[
			'build',
			'--target:js',
			join(root, 'dafny/LoginThrottle.dfy'),
			'--output',
			join(work, 'out')
		],
		{
			stdio: ['ignore', 'inherit', 'inherit'],
			env: { ...process.env, NODE_PATH: join(root, 'node_modules') }
		}
	);
	const js = readFileSync(join(work, 'out.js'), 'utf8')
		.replace("const BigNumber = require('bignumber.js');", "import BigNumber from 'bignumber.js';")
		.replace(/\nlet _module = \(function\(\) \{[\s\S]*$/, '\n');
	if (js.includes('require(')) throw new Error('unexpected require() left in Dafny output');
	const out = join(root, 'src/lib/server/generated');
	mkdirSync(out, { recursive: true });
	writeFileSync(
		join(out, 'login-throttle-core.js'),
		`// @ts-nocheck\n// GENERATED by scripts/build-dafny.mjs from dafny/LoginThrottle.dfy. Do not edit.\n${js}\nexport { _dafny, LoginThrottleCore };\n`
	);
} finally {
	rmSync(work, { recursive: true, force: true });
}
